package reviewtransaction

import (
	"bytes"
	"context"
	"errors"
	"path/filepath"
	"strconv"
	"strings"
)

// T3 fork: reviewers get the metadata summary golden files get for code-generator
// output and ODD logbooks too. Their hunks repeat what reviewed input already says
// (one Convex _generated module is often hundreds of KB) or record the agent's own
// process, and they filled the reviewer context budget. Risk classification does
// not use these rules.

// isGeneratedCodePath recognizes the common code-generator output path conventions.
func isGeneratedCodePath(logicalPath string) bool {
	normalized := "/" + strings.TrimPrefix(filepath.ToSlash(logicalPath), "./")
	if strings.Contains(normalized, "/_generated/") || strings.Contains(normalized, "/__generated__/") {
		return true
	}
	base := normalized[strings.LastIndex(normalized, "/")+1:]
	return strings.Contains(base, ".gen.") || strings.Contains(base, ".generated.") ||
		strings.HasPrefix(base, "zz_generated.") || strings.HasSuffix(base, ".pb.go") ||
		strings.HasSuffix(base, "_pb2.py") || strings.HasSuffix(base, "_pb2_grpc.py")
}

// isWorkflowLogbookPath recognizes ODD feature documents. Checking a change against
// their specs is verification's job, not review's.
func isWorkflowLogbookPath(logicalPath string) bool {
	normalized := "/" + strings.TrimPrefix(filepath.ToSlash(logicalPath), "./")
	return strings.HasPrefix(normalized, "/odd/") && strings.HasSuffix(normalized, ".md")
}

// generatedHeaderPattern matches the markers generators write at the top of their
// output: "@generated", "auto-generated", "Generated file", "Code generated by",
// "This file was automatically generated".
const generatedHeaderPattern = `@generated|auto-?generated|generated (file|code)|code generated|(is|was) (automatically |auto-)?generated`

// generatedHeaderLines bounds where the marker counts: a header, not a mention.
const generatedHeaderLines = 5

const generatedHeaderPathsPerGrep = 200

// markGeneratedHeaders marks every changed text file whose header declares it
// generated, so generators the path rules miss (kitcn's convex/generated/*.ts) are
// summarized too. It reads the frozen candidate tree, so START and STATUS agree.
func markGeneratedHeaders(ctx context.Context, repo string, isolation []string, candidateTree string, manifest []ChangedPathManifestEntry) error {
	pending := make([]int, 0, len(manifest))
	for index, entry := range manifest {
		if !entry.Generated && !entry.Deleted {
			pending = append(pending, index)
		}
	}
	for start := 0; start < len(pending); start += generatedHeaderPathsPerGrep {
		batch := pending[start:min(start+generatedHeaderPathsPerGrep, len(pending))]
		// -m 1 -o keeps each file to its first marker, so a minified line never
		// floods the output.
		args := []string{"grep", "-z", "-n", "-I", "-i", "-E", "-o", "-m", "1", "-e", generatedHeaderPattern, candidateTree, "--"}
		for _, index := range batch {
			args = append(args, ":(literal)"+manifest[index].Path)
		}
		output, err := runGitLimited(ctx, repo, isolation, nil, len(batch)*512, args...)
		if err != nil {
			var commandErr *GitCommandError
			if errors.As(err, &commandErr) && commandErr.ExitCode == 1 {
				continue // git grep exits 1 when nothing matched
			}
			return err
		}
		declared := generatedHeaderMatches(output, candidateTree)
		for _, index := range batch {
			if declared[manifest[index].Path] {
				manifest[index].Generated = true
			}
		}
	}
	return nil
}

// generatedHeaderMatches parses `git grep -z -n` records, "<tree>:<path>\0<line>\0<match>",
// into the paths whose first marker sits in the header.
func generatedHeaderMatches(output []byte, candidateTree string) map[string]bool {
	declared := map[string]bool{}
	for _, record := range bytes.Split(output, []byte{'\n'}) {
		fields := bytes.SplitN(record, []byte{0}, 3)
		if len(fields) != 3 {
			continue
		}
		line, err := strconv.Atoi(string(fields[1]))
		if err != nil || line > generatedHeaderLines {
			continue
		}
		declared[strings.TrimPrefix(string(fields[0]), candidateTree+":")] = true
	}
	return declared
}
