func TestGeneratedCandidatePathRecognizesCodeGeneratorOutput(t *testing.T) {
	tests := []struct {
		name string
		path string
		want bool
	}{
		{name: "convex generated module", path: "packages/sdk/convex/actos/_generated/plantillas_cota.ts", want: true},
		{name: "convex generated api", path: "convex/_generated/api.d.ts", want: true},
		{name: "relay artifacts", path: "src/__generated__/UserQuery.graphql.ts", want: true},
		{name: "tanstack route tree", path: "apps/web/.tanstack/routeTree.gen.ts", want: true},
		{name: "generated infix", path: "src/client.generated.ts", want: true},
		{name: "kubernetes deepcopy", path: "api/v1/zz_generated.deepcopy.go", want: true},
		{name: "protobuf go", path: "proto/user.pb.go", want: true},
		{name: "protobuf python", path: "proto/user_pb2.py", want: true},
		{name: "grpc python", path: "proto/user_pb2_grpc.py", want: true},
		{name: "generator source", path: "scripts/build-plantillas-cota.ts", want: false},
		{name: "generated word in a directory name", path: "docs/generated-reports/summary.md", want: false},
		{name: "underscore directory near miss", path: "src/_generated_helpers/index.ts", want: false},
		{name: "gen prefix near miss", path: "src/general.ts", want: false},
		{name: "pb suffix near miss", path: "proto/user.pb.go.txt", want: false},
		{name: "odd logbook", path: "odd/tasks/plantillas-resolucion-cota.md", want: true},
		{name: "doc about odd", path: "docs/odd.md", want: false},
		{name: "code under odd", path: "odd/tasks/x.ts", want: false},
		{name: "product doc", path: "docs/product/solicitudes.md", want: false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := isGeneratedCandidatePath(tt.path); got != tt.want {
				t.Fatalf("isGeneratedCandidatePath(%q) = %t, want %t", tt.path, got, tt.want)
			}
		})
	}
}

func TestFrozenCandidateContextSummarizesFilesWhoseHeaderDeclaresThemGenerated(t *testing.T) {
	requireSnapshotGit(t)
	repo := initSnapshotRepo(t)
	writeSnapshotFile(t, repo, "convex/generated/auth.ts", "/* eslint-disable */\n// This file is auto-generated by kitcn\n// Do not edit manually\nexport const auth = 1;\n")
	writeSnapshotFile(t, repo, "src/handwritten.ts", strings.Repeat("export const x = 1;\n", 19)+"// the client is auto-generated elsewhere\n")
	writeSnapshotFile(t, repo, "src/plain.ts", "export const y = 2;\n")
	paths := []string{"convex/generated/auth.ts", "src/handwritten.ts", "src/plain.ts"}
	snapshot, err := (SnapshotBuilder{Repo: repo}).Build(context.Background(), Target{
		Kind: TargetCurrentChanges, Projection: ProjectionWorkspace, IntendedUntracked: paths,
	})
	if err != nil {
		t.Fatalf("Build() error = %v", err)
	}
	contextResult, err := (SnapshotBuilder{Repo: repo}).FrozenCandidateContext(context.Background(), snapshot)
	if err != nil {
		t.Fatalf("FrozenCandidateContext() error = %v", err)
	}
	want := map[string]bool{"convex/generated/auth.ts": true, "src/handwritten.ts": false, "src/plain.ts": false}
	if len(contextResult.ChangedPathManifest) != len(want) {
		t.Fatalf("manifest = %#v, want %d entries", contextResult.ChangedPathManifest, len(want))
	}
	for _, entry := range contextResult.ChangedPathManifest {
		if entry.Generated != want[entry.Path] {
			t.Errorf("%s Generated = %t, want %t", entry.Path, entry.Generated, want[entry.Path])
		}
	}
}
